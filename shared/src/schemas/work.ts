import { z } from 'zod';
import { id, requestId, text, version } from './student';
import { SENT_STATUSES, WORK_STATUSES } from '../constants/work-status';
export const year = z.number().int().min(2500).max(3000);
export const classRefSchema = z.object({ classId: id }).strict();
export const createClassSchema = z.object({ requestId, year, term: z.union([z.literal(1), z.literal(2)]), subject: text, group: text }).strict();
export const subjectSchema = z.object({ requestId, name: text }).strict();
export const createTaskSchema = z.object({ requestId, classId: id, name: text.optional() }).strict();
export const renameTaskSchema = z.object({ requestId, classId: id, taskId: id, expectedVersion: version, name: text }).strict();
export const deleteTaskSchema = z.object({ requestId, classId: id, taskId: id, expectedVersion: version, confirmed: z.literal(true) }).strict();
export const qrPayload = z.string().min(1).max(2048);
export const resolveQrSchema = z.object({ payload: qrPayload }).strict();
export const scanSchema = z.object({ requestId, payload: qrPayload, status: z.enum(SENT_STATUSES) }).strict();
export const pastWorkSchema = scanSchema.extend({ taskId: id, confirmed: z.literal(true) }).strict();
export const changeWorkSchema = z.object({ requestId, classId: id, studentId: id, taskId: id, expectedVersion: version, status: z.enum(WORK_STATUSES), confirmClear: z.boolean().default(false) }).strict();
export const getWorkSchema = z.object({ classId: id, studentId: id, taskId: id }).strict();
export const qrDownloadSchema = z.object({ classId: id, studentId: id.optional() }).strict();
export const resultSchema = z.object({ requestId }).strict();
export type ScanInput = z.infer<typeof scanSchema>;
export type ChangeWorkInput = z.infer<typeof changeWorkSchema>;
